/* Нейтральные тексты-заглушки для модулей, книги и ответов AXON.
   Настоящие тексты курса сюда не копируются. */
(function (PM) {
  'use strict';
  const P = [
    'Это абзац-заглушка. Он нужен, чтобы проверить, как читается длинный текст на светлой «бумаге»: длина строки, межстрочный интервал, отступы между абзацами и переносы слов. В настоящем кабинете здесь будет текст раздела из книги курса.',
    'Второй абзац тоже заглушка. Обратите внимание, что строка не шире примерно 68 знаков, текст выровнен по левому краю, а переносы расставляет браузер. Так глаз меньше устаёт на длинных главах, особенно на телефоне.',
    'Короткий абзац для ритма.',
    'Здесь мог бы быть пример из практики. В макете он нарочно обезличен: ни имён, ни подробностей. Задача этого текста — показать, как выглядит обычный абзац среди заголовков, списков и выделенных мыслей.',
    'Заключительный абзац раздела. После него идёт переход к следующему разделу или к заданию модуля, если раздел последний.',
  ];
  const KEY = 'Главная мысль раздела выделена полосой слева. В книге таких мест немного, поэтому их легко найти при повторении.';
  const LIST = ['Первый пункт списка-заглушки', 'Второй пункт: чуть длиннее, чтобы проверить перенос строки внутри пункта списка', 'Третий пункт'];

  function moduleSections(n) {
    return [1, 2, 3, 4].map((k) => ({
      id: `s${k}`,
      title: `${k}. Заголовок раздела ${n}.${k}`,
      blocks: k === 1
        ? [{ t: 'lead', text: 'Подзаголовок модуля — одна строка о том, о чём этот модуль. Текст-заглушка.' }, { t: 'p', text: P[0] }, { t: 'p', text: P[1] }, { t: 'key', text: KEY }, { t: 'p', text: P[3] }]
        : k === 2 ? [{ t: 'p', text: P[1] }, { t: 'ul', items: LIST }, { t: 'p', text: P[2] }, { t: 'p', text: P[4] }]
          : [{ t: 'p', text: P[3] }, { t: 'p', text: P[0] }, { t: 'p', text: P[4] }],
    }));
  }
  function bookChapters(modules) {
    const intro = [{ id: 'intro', title: 'Введение', sections: [{ id: 'intro-1', title: 'О книге', blocks: [{ t: 'p', text: P[0] }, { t: 'p', text: P[1] }] }, { id: 'intro-2', title: 'Как читать', blocks: [{ t: 'p', text: P[3] }, { t: 'key', text: KEY }] }] }];
    return intro.concat(modules.map((m) => ({ id: 'm' + m.n, title: m.title, module: m.n, sections: moduleSections(m.n).map((s) => ({ ...s, id: `m${m.n}-${s.id}` })) })));
  }
  /* Ответы AXON — про учёбу в целом, без содержания курса */
  function axonAnswer(q) {
    const t = q.toLowerCase();
    if (t.includes('домаш') || t.includes('задан')) return 'Давайте разобьём задание на шаги:\n\n- **Вопрос 1** — опишите ситуацию без выводов, 5–7 предложений.\n- **Вопрос 2** — разложите её по схеме из модуля.\n- **Вопросы 3–4** — выбор приёма и короткий вывод.\n\nЧерновик сохраняется сам, так что можно делать по одному вопросу в день. С какого начнём?';
    if (t.includes('повтор') || t.includes('план')) return 'Удобный план повторения:\n\n- **Сегодня** — 10 минут: выписать три главные мысли модуля.\n- **Через два дня** — пересказать их без конспекта.\n- **Перед встречей** — сверить пересказ с книгой.\n\nХотите, составлю такой план для конкретного модуля?';
    return 'Хороший вопрос. Коротко:\n\n- сначала сформулируйте, что именно непонятно, одной фразой;\n- затем найдите в книге раздел, где это объясняется, — я могу подсказать главу;\n- после чтения попробуйте объяснить своими словами.\n\nЭто ответ-заглушка прототипа: в настоящем кабинете AXON отвечает с опорой на книгу курса.';
  }
  const axonSuggestions = ['Составь план повторения модуля', 'Помоги начать домашнее задание', 'Объясни термин из книги простыми словами'];
  PM.content = { moduleSections, bookChapters, axonAnswer, axonSuggestions };
})(window.PM);
